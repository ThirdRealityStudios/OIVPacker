#ifndef PROJECT_OIV_XMLPARSER_H
#define PROJECT_OIV_XMLPARSER_H

#include "types.h"

/// @brief Copies tag areas by their name to a list,
///		   e.g. if you enter "foo" for argument "tagName"
///        and argument "xmlDoc" refers to a string like
///        "<bigXml><foo>some text</foo><abc>Hello</abc><foo>Nice</foo></bigXml>",
///		   then your list will contain in the end the two elements with values
/// 	   "<foo>some text</foo>" and "<foo>Nice</foo>".
/// @param xmlDoc The XML string to be processed.
/// @param tagName The tag name used to fetch the corresponding strings.
/// @return A list with the found strings. Otherwise an empty list.
List *getStringsByTagName(char *xmlDoc, char *tagName);

/// @brief Providing a string, e.g. generated by getStringsByTagName(),
///		   you can retrieve the value of a tag here.
///        Example: you provide for "tagString"
///		   the value "<tag foo="aValue">Content between</tag>"
///		   and for "attributeName" the value "foo".
///        What is being returned is then the string "aValue".
///        That also means you need to ensure a valid XML string.
///	@param tagString Tag string of the explained format.
/// @param attributeName Attribute name used to returned the assigned value from.
/// @return Value of the attribute (make sure to call free() to the returned string if not needed anymore!).
char* getValueByAttributeName(char *tagString, char *attributeName);

/// @brief Returns the name of the first XML tag appearing in a string.
///		   E.g., if you have "lorem ipsum<tag></tag>hello<bold> world</bold>",
///		   it is going to return the string "tag".
///        Anyway, be aware that this string would also return "tag":
///		   "lorem ipsum<tag></DIFFERENT>hello<bold> world</bold>".
///        Hence, this function does not care about the semantical
///        structure of your XML code!
///        It will simply and always return the first pattern of "<...>" appearing.
/// @param xmlString Your XML string
/// @return XML tag name or NULL if no tag name found (then your XML document is invalid).
char *getFirstTagNameByXmlString(char *xmlString);

/// @brief Required a valid XML tag string of the format "<yourTag>someContent</yourTag>",
///        this function will return the content area of your XML tag string.
///        In the example case as just mentioned, this would be "someContent" in this case.
/// 	   This function will not work as you might want, e.g. if you provide multiple tags in a string.
///		   Take this here: "<foo>alsoSomeContent</foo><anotherTag>Hello</anotherTag>".
///        The returned string would be in this case "alsoSomeContent",
///        so always the first tags content area will be returned (if thought it might be the second).
///		   If the tagString parameter is this "<foo>alsoSomeContent</nonSense>",
///		   then this function will return NULL because this is no valid XML.
/// @param tagString Tag string as just described briefly
/// @return Content area string as also just described.
char* getContentByTagString(char *tagString);

#endif